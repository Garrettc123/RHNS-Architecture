-- RHNS Agentic System — Supabase Schema
-- Run this in your Supabase SQL Editor

create table if not exists rhns_episodes (
  id bigint generated by default as identity primary key,
  goal text not null,
  trajectory jsonb not null default '[]'::jsonb,
  outcome text not null default 'pending',
  created_at timestamptz not null default now(),
  operator_count integer not null default 0
);

-- Enable full-text search on goal column
create index if not exists idx_rhns_episodes_goal_fts
  on rhns_episodes using gin(to_tsvector('english', goal));

-- Optional: graph memory table for Tier 4 GraphRAG
create table if not exists rhns_graph_memory (
  id bigint generated by default as identity primary key,
  node_id text not null unique,
  node_type text not null,
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_rhns_graph_memory_node_type
  on rhns_graph_memory(node_type);

-- Row-level security
alter table rhns_episodes enable row level security;
alter table rhns_graph_memory enable row level security;

create policy if not exists "Authenticated users can manage episodes"
  on rhns_episodes for all
  to authenticated
  using (true)
  with check (true);

create policy if not exists "Authenticated users can manage graph memory"
  on rhns_graph_memory for all
  to authenticated
  using (true)
  with check (true);